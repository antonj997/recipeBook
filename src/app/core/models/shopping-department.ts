function classifyProduct(text: string): ShoppingDepartmentId {
  for (const { department, pattern } of specificRules) if (pattern.test(text)) return department;
  // The first product in a description is the item; serving/preparation mentions come later.
  let chosen: ShoppingDepartmentId = 'other';
  let first = Infinity;
  for (const { department, pattern } of ingredientRules) {
    const match = pattern.exec(text);
    if (match && match.index < first) {
      chosen = department;
      first = match.index;
    }
  }
  return chosen;
}

export function shoppingDepartment(text: string): ShoppingDepartmentId {
  const normalized = text
    .toLocaleLowerCase('sv-SE')
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .replace(/\(([^)]*)\)/g, (_match, note: string) =>
      /^(?:fryst[ae]?|frusen|frozen)$/.test(note.trim()) ? ' ' + note + ' ' : ' ',
    )
    .split(/,(?!\d)|;|\b(?:eller|or)\b/)[0]
    .replace(/&|\+/g, ' och ')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const departments = new Set(normalized.split(/\b(?:och|and)\b/).map(classifyProduct));
  departments.delete('other');
  return departments.size === 1 ? (departments.values().next().value ?? 'other') : 'other';
}

export function groupByShoppingDepartment(
  groups: readonly ShoppingGroup[],
): ShoppingDepartmentGroup[] {
  const buckets = new Map<ShoppingDepartmentId, ShoppingGroup[]>();
  for (const group of groups) {
    const id = shoppingDepartment(group.text);
    const bucket = buckets.get(id);
    if (bucket) bucket.push(group);
    else buckets.set(id, [group]);
  }
  return shoppingDepartments.flatMap(({ id, label }) => {
    const rows = buckets.get(id);
    return rows ? [{ id, label, groups: rows }] : [];
  });
}
