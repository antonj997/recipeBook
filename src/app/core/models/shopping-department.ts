type Rule = { department: ShoppingDepartmentId; pattern: RegExp };
function rule(department: ShoppingDepartmentId, ...terms: string[]): Rule {
  return { department, pattern: new RegExp('\\b(?:' + terms.join('|') + ')\\b', 'u') };
}

